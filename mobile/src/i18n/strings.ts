export type Locale = 'en' | 'fr' | 'ar' | 'tn'

export const LOCALES: { id: Locale, name: string, rtl: boolean }[] = [
  { id: 'en', name: 'English', rtl: false },
  { id: 'fr', name: 'Français', rtl: false },
  { id: 'ar', name: 'العربية', rtl: true },
  { id: 'tn', name: 'تونسي', rtl: true },
]

export const isRtl = (locale: Locale) => locale === 'ar' || locale === 'tn'

export function translate(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  const table: Partial<Record<StringKey, string>> = locale === 'fr' ? fr : locale === 'en' ? en : ar
  let text = table[key] ?? en[key]
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value))
  return text
}
